export type TKey = keyof (typeof dict)["ar"];

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  const table = dict[lang] as Record<string, string>;
  let value = table[key] ?? (dict.en as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const [name, v] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(v));
    }
  }
  return value;
}

